function loadEnvKey() {
  const envPath = path.join(root, ".env.local");
  if (!fs.existsSync(envPath)) return undefined;
  const text = fs.readFileSync(envPath, "utf8");
  for (const line of text.split("\n")) {
    const m = line.match(/^\s*(?:RAPIDAPI_KEY|FOOTBALL_API_KEY)\s*=\s*(.+?)\s*$/);
    if (m) return m[1].replace(/^["']|["']$/g, "");
  }
  return undefined;
}

function getSofascoreHost() {
  const envPath = path.join(root, ".env.local");
  if (!fs.existsSync(envPath)) return "sofascore.p.rapidapi.com";
  const text = fs.readFileSync(envPath, "utf8");
  const m = text.match(/^\s*FOOTBALL_PRIMARY_PROVIDER\s*=\s*(.+?)\s*$/m);
  const host = m?.[1]?.replace(/^["']|["']$/g, "").trim();
  if (host?.includes("rapidapi.com")) return host.replace(/^https?:\/\//i, "").replace(/\/+$/, "");
  return "sofascore.p.rapidapi.com";
}

function collectTeamsFromSource(filePath) {
  const text = fs.readFileSync(filePath, "utf8");
  const teams = [];
  const blockRegex = /\{\s*id:\s*(\d+),\s*name:\s*"([^"]+)"\s*\}/g;
  let m;
  while ((m = blockRegex.exec(text)) !== null) {
    teams.push({ id: Number(m[1]), name: m[2] });
  }
  return teams;
}

function normalizeTeamName(name) {
  const base = name
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[.,''"()\-_/]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/&/g, "and");
  return base
    .split(" ")
    .map((t) => t.trim())
    .filter(Boolean)
    .filter((t) => !TEAM_STOPWORDS.has(t))
    .join(" ");
}

function uniqueTeams(teams) {
  const byId = new Map();
  for (const t of teams) {
    if (!t.id || !t.name) continue;
    const existing = byId.get(t.id);
    byId.set(t.id, {
      id: t.id,
      name: t.name,
      shortName: t.shortName?.trim() || existing?.shortName,
      slug: t.slug?.trim() || existing?.slug,
    });
  }
  return [...byId.values()];
}

function writeManifest(teams) {
  const sorted = [...teams].sort((a, b) => a.name.localeCompare(b.name));
  const idToName = Object.fromEntries(sorted.map((t) => [t.id, t.name]));
  const nameToId = {};
  for (const t of sorted) {
    const keys = new Set([normalizeTeamName(t.name)]);
    if (t.shortName) keys.add(normalizeTeamName(t.shortName));
    if (t.slug) keys.add(t.slug.toLowerCase().replace(/-/g, " "));
    const iso = NATIONAL_NAME_TO_ISO[t.name];
    if (iso) keys.add(iso);

    for (const key of keys) {
      if (key && !(key in nameToId)) nameToId[key] = t.id;
    }
  }

  const out = `// AUTO-GENERATED by scripts/download-team-logos.mjs\n// Do not edit by hand.\n// Team ids are SofaScore / SportAPI canonical ids.\n\nexport const TEAM_LOGO_ID_TO_NAME: Record<number, string> = ${JSON.stringify(idToName, null, 2)};\n\nexport const TEAM_LOGO_NAME_TO_ID: Record<string, number> = ${JSON.stringify(nameToId, null, 2)};\n`;

  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
  fs.writeFileSync(manifestPath, out, "utf8");
}

async function sofascoreGet(apiKey, host, route, query) {
  const params = new URLSearchParams(
    Object.fromEntries(Object.entries(query).map(([k, v]) => [k, String(v)]))
  );
  const url = `https://${host}/${route}?${params}`;
  const res = await fetch(url, {
    headers: {
      "x-rapidapi-key": apiKey,
      "x-rapidapi-host": host,
    },
  });
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`${route} HTTP ${res.status}: ${text.slice(0, 200)}`);
  }
  return res.json();
}

async function fetchCurrentSeasonId(apiKey, host, tournamentId) {
  const data = await sofascoreGet(apiKey, host, "tournaments/get-seasons", {
    tournamentId,
  });
  const season = data.seasons?.[0];
  if (!season?.id) throw new Error(`No season for tournament ${tournamentId}`);
  return season.id;
}

function collectTeamsFromStandings(data) {
  const teams = [];
  for (const group of data.standings ?? []) {
    for (const row of group.rows ?? []) {
      const team = row.team;
      if (!team?.id || !team?.name) continue;
      teams.push({
        id: team.id,
        name: team.name,
        shortName: team.shortName,
        slug: team.slug,
      });
    }
  }
  return teams;
}

async function fetchLeagueTeams(apiKey, host, tournamentId) {
  const seasonId = await fetchCurrentSeasonId(apiKey, host, tournamentId);
  const data = await sofascoreGet(apiKey, host, "tournaments/get-standings", {
    tournamentId,
    seasonId,
  });
  return collectTeamsFromStandings(data);
}

async function downloadBytes(url, headers) {
  const res = await fetch(url, { redirect: "follow", headers });
  if (!res.ok) return null;
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 200) return null;
  return buf;
}

async function downloadSofascoreLogo(apiKey, host, teamId) {
  const url = `https://${host}/teams/get-logo?teamId=${teamId}`;
  return downloadBytes(url, {
    "x-rapidapi-key": apiKey,
    "x-rapidapi-host": host,
  });
}

async function main() {
  const apiKey = loadEnvKey();
  if (!apiKey) {
    console.error("Missing RAPIDAPI_KEY in .env.local");
    process.exit(1);
  }

  const force = process.argv.includes("--force");

  const host = getSofascoreHost();
  const wcPath = path.join(root, "src/lib/data/world-cup-2026-teams.ts");
  const wcTeams = uniqueTeams(collectTeamsFromSource(wcPath));
  let teams = [...wcTeams];
  let clubTeamsFromLeagues = 0;

  console.log(`SofaScore host: ${host}`);
  console.log(`Fetching club teams from ${UNIQUE_TOURNAMENT_IDS.length} competitions…`);

  for (const tournamentId of UNIQUE_TOURNAMENT_IDS) {
    try {
      const fromLeague = await fetchLeagueTeams(apiKey, host, tournamentId);
      clubTeamsFromLeagues += fromLeague.length;
      teams = uniqueTeams([...teams, ...fromLeague]);
      process.stdout.write(`  tournament ${tournamentId}: ${fromLeague.length} teams\n`);
    } catch (err) {
      process.stdout.write(`  tournament ${tournamentId}: skip (${err.message})\n`);
    }
    await new Promise((r) => setTimeout(r, 120));
  }

  const minClubTeamsForManifest = 80;
  if (clubTeamsFromLeagues < minClubTeamsForManifest) {
    console.warn(
      `\nOnly ${clubTeamsFromLeagues} club teams from leagues (API quota/errors). ` +
        `Keeping existing team-logo-manifest.ts — run npm run logos:repair to fix badge files.`
    );
    const manifestText = fs.readFileSync(manifestPath, "utf8");
    const existing = [];
    for (const m of manifestText.matchAll(/"(\d+)":\s*"([^"]+)"/g)) {
      existing.push({ id: Number(m[1]), name: m[2] });
    }
    teams = uniqueTeams([...existing, ...teams]);
  } else {
    writeManifest(teams);
  }

  console.log(`\nTotal unique teams: ${teams.length}`);
  fs.mkdirSync(outDir, { recursive: true });

  let ok = 0;
  let fail = 0;
  let skipped = 0;

  for (const team of teams) {
    const dest = path.join(outDir, `${team.id}.png`);
    if (!force && fs.existsSync(dest) && fs.statSync(dest).size > 200) {
      skipped++;
      continue;
    }

    const iso = NATIONAL_NAME_TO_ISO[team.name];
    let saved = false;

    if (iso) {
      const flagBuf = await downloadBytes(`https://flagcdn.com/w160/${iso}.png`);
      if (flagBuf) {
        fs.writeFileSync(dest, flagBuf);
        ok++;
        saved = true;
        process.stdout.write(`✓ ${team.id} ${team.name} (flag)\n`);
      }
    }

    if (!saved) {
      try {
        const buf = await downloadSofascoreLogo(apiKey, host, team.id);
        if (buf) {
          fs.writeFileSync(dest, buf);
          ok++;
          saved = true;
          process.stdout.write(`✓ ${team.id} ${team.name}\n`);
        }
      } catch {
        /* try api-sports fallback below */
      }
    }

    if (!saved) {
      fail++;
      process.stdout.write(`✗ ${team.id} ${team.name}\n`);
    }

    await new Promise((r) => setTimeout(r, 90));
  }

  console.log(
    `\nDone: ${ok} downloaded, ${skipped} already present, ${fail} missing → public/team-logos/`
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});

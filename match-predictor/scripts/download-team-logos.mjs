function collectTeamsFromSource(filePath) {
  const text = fs.readFileSync(filePath, "utf8");
  const teams = [];
  const blockRegex = /\{\s*id:\s*(\d+),\s*name:\s*"([^"]+)"\s*\}/g;
  let m;
  while ((m = blockRegex.exec(text)) !== null) {
    teams.push({ id: Number(m[1]), name: m[2] });
  }
  return teams;
}

function uniqueTeams(teams) {
  const byId = new Map();
  for (const t of teams) byId.set(t.id, t);
  return [...byId.values()];
}

function normalizeTeamName(name) {
  return name
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ")
    .replace(/&/g, "and");
}

function writeManifest(teams) {
  const sorted = [...teams].sort((a, b) => a.name.localeCompare(b.name));
  const idToName = Object.fromEntries(sorted.map((t) => [t.id, t.name]));
  const nameToId = Object.fromEntries(sorted.map((t) => [normalizeTeamName(t.name), t.id]));

  const out = `// AUTO-GENERATED by scripts/download-team-logos.mjs\n// Do not edit by hand.\n\nexport const TEAM_LOGO_ID_TO_NAME: Record<number, string> = ${JSON.stringify(idToName, null, 2)};\n\nexport const TEAM_LOGO_NAME_TO_ID: Record<string, number> = ${JSON.stringify(nameToId, null, 2)};\n`;

  fs.mkdirSync(path.dirname(manifestPath), { recursive: true });
  fs.writeFileSync(manifestPath, out, "utf8");
}

async function download(url) {
  const res = await fetch(url, { redirect: "follow" });
  if (!res.ok) return null;
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 200) return null;
  return buf;
}

async function main() {
  const refPath = path.join(root, "src/lib/data/football-reference.ts");
  const wcPath = path.join(root, "src/lib/data/world-cup-2026-teams.ts");
  const teams = uniqueTeams([
    ...collectTeamsFromSource(refPath),
    ...collectTeamsFromSource(wcPath),
  ]);

  fs.mkdirSync(outDir, { recursive: true });
  writeManifest(teams);

  let ok = 0;
  let fail = 0;

  for (const team of teams) {
    const dest = path.join(outDir, `${team.id}.png`);
    if (fs.existsSync(dest) && fs.statSync(dest).size > 200) {
      ok++;
      continue;
    }

    const iso = NATIONAL_NAME_TO_ISO[team.name];
    const sources = iso
      ? [`https://flagcdn.com/w160/${iso}.png`, `https://media.api-sports.io/football/teams/${team.id}.png`]
      : [`https://media.api-sports.io/football/teams/${team.id}.png`];

    let saved = false;
    for (const url of sources) {
      try {
        const buf = await download(url);
        if (buf) {
          fs.writeFileSync(dest, buf);
          ok++;
          saved = true;
          process.stdout.write(`✓ ${team.id} ${team.name}\n`);
          break;
        }
      } catch {
        /* try next */
      }
    }

    if (!saved) {
      fail++;
      process.stdout.write(`✗ ${team.id} ${team.name}\n`);
    }

    await new Promise((r) => setTimeout(r, 80));
  }

  console.log(`\nDone: ${ok} saved, ${fail} missing → public/team-logos/`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
